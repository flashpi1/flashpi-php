<?php

declare(strict_types=1);

namespace Flashpi\Scripts\OpenApi;

/**
 * Turns the Flashpi OpenAPI document into PHPStan type aliases (src/Types/ApiTypes.php).
 *
 * Every component schema becomes a `@phpstan-type`: an object becomes an array shape with the
 * API's camelCase keys (optional keys marked `?`, nullable members `|null`), an enum a union of
 * literals, and the query of every list operation a shape named after it (`DocumentsListQuery`).
 * Inline objects and enums get a name of their own, made of their schema's and property's names
 * (`DocumentStatus`). The output is deterministic, and any construct the generator does not know
 * fails the generation, so a change in the document is never translated into a wrong type.
 */
final class Generator
{
    public const HEADER = <<<'TEXT'
        Types of the Flashpi API, generated from its public OpenAPI document.

        GENERATED by scripts/openapi.php from openapi/openapi.json. Do not edit by hand: run
        `composer openapi:sync` (or `composer openapi:generate`).

        Each type is a PHPStan type alias: models are arrays with the API's camelCase keys, as
        json_decode() returns them. Import one in your own PHPDoc with
        `@phpstan-import-type Document from \Flashpi\Types\ApiTypes`. Error codes are open: the API
        may add codes, so any string is accepted where one is expected.
        TEXT;

    /** The longest line before a union is written one member per line. */
    private const LINE_LENGTH = 100;

    private const INDENT = '    ';

    /** Keywords that only constrain or document values: an array shape cannot express them. */
    private const ANNOTATION_KEYWORDS = [
        'description', 'example', 'examples', 'format', 'pattern', 'minLength', 'maxLength',
        'minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'multipleOf', 'minItems',
        'maxItems', 'uniqueItems', 'minProperties', 'maxProperties', 'default', 'title',
        'deprecated',
    ];

    private const STRUCTURE_KEYWORDS = [
        'type', 'properties', 'required', 'items', 'enum', 'const', '$ref', 'allOf', 'anyOf',
        'oneOf', 'discriminator', 'additionalProperties', 'not',
    ];

    private const SCALARS = [
        'string' => 'string',
        'integer' => 'int',
        'number' => 'int|float',
        'boolean' => 'bool',
        'null' => 'null',
    ];

    /**
     * Error codes the API may add to: wherever a schema refers to one, any string is accepted
     * (`ErrorCode|string`), so code that compares an unknown code still passes analysis.
     */
    private const OPEN_ENUMS = ['ErrorCode', 'FieldErrorCode'];

    /** Names PHPStan reads as types of its own: an alias cannot take them. */
    private const RESERVED_NAMES = [
        'array', 'bool', 'boolean', 'callable', 'class-string', 'double', 'false', 'float',
        'int', 'integer', 'iterable', 'list', 'mixed', 'never', 'null', 'number', 'numeric',
        'object', 'resource', 'scalar', 'self', 'static', 'string', 'true', 'void', 'parent',
    ];

    private const COMPONENT_PREFIX = '#/components/schemas/';

    private const PARAMETER_PREFIX = '#/components/parameters/';

    /** @var array<string, mixed> */
    private readonly array $document;

    /** @var array<string, mixed> */
    private readonly array $schemas;

    /** @var array<string, mixed> */
    private readonly array $parameters;

    /** @var array<string, Definition> */
    private array $definitions = [];

    /**
     * @param mixed $document The decoded OpenAPI document (json_decode(..., true)).
     */
    public function __construct(mixed $document)
    {
        $this->document = self::schema($document, 'document');
        $version = $this->document['openapi'] ?? null;
        if (!\is_string($version) || !str_starts_with($version, '3.1')) {
            throw new GenerationError('Only OpenAPI 3.1 documents are supported');
        }
        $components = self::schema($this->document['components'] ?? [], 'components');
        $this->schemas = self::schema($components['schemas'] ?? [], 'components.schemas');
        $this->parameters = self::schema($components['parameters'] ?? [], 'components.parameters');
    }

    /**
     * The PHP source of src/Types/ApiTypes.php for a contract.
     */
    public static function fromContract(string $contract): string
    {
        try {
            $document = json_decode($contract, true, 512, \JSON_THROW_ON_ERROR);
        } catch (\JsonException $error) {
            throw new GenerationError('The contract is not JSON: ' . $error->getMessage(), 0, $error);
        }

        return (new self($document))->generate();
    }

    public function generate(): string
    {
        $schemas = $this->schemas;
        ksort($schemas, \SORT_STRING);
        foreach ($schemas as $name => $schema) {
            $this->defineComponent($name, self::schema($schema, $name));
        }
        $this->defineQueries();
        $this->checkCycles();

        $sorted = $this->definitions;
        ksort($sorted, \SORT_STRING);
        $lines = ['<?php', '', 'declare(strict_types=1);', '', 'namespace Flashpi\\Types;', '', '/**'];
        foreach (explode("\n", self::HEADER) as $line) {
            $lines[] = rtrim(' * ' . $line);
        }
        $lines[] = ' *';
        foreach ($sorted as $definition) {
            foreach ($this->emit($definition) as $line) {
                $lines[] = ' * ' . $line;
            }
        }
        $lines[] = ' */';
        $lines[] = 'final class ApiTypes';
        $lines[] = '{';
        $lines[] = self::INDENT . 'private function __construct() {}';
        $lines[] = '}';

        return implode("\n", $lines) . "\n";
    }

    // Translation of schemas into type expressions.

    /**
     * @param array<string, mixed> $schema
     *
     * @return array{string, list<string>} The expression and the definitions it uses.
     */
    private function render(array $schema, string $hint, string $where, bool $top = false): array
    {
        $this->checkKeywords($schema, $where);
        if (\array_key_exists('$ref', $schema)) {
            $name = $this->reference($schema, $where);

            return [\in_array($name, self::OPEN_ENUMS, true) ? $name . '|string' : $name, [$name]];
        }
        foreach (['allOf', 'anyOf', 'oneOf'] as $combinator) {
            if (\array_key_exists($combinator, $schema)) {
                return $this->renderCombination($schema, $combinator, $hint, $where);
            }
        }
        $types = $this->typesOf($schema, $where);
        $nullable = \in_array('null', $types, true);
        $types = array_values(array_filter($types, static fn(string $kind): bool => $kind !== 'null'));
        if (\array_key_exists('not', $schema) && $types !== ['object']) {
            throw new GenerationError("{$where}: `not` is only supported on objects");
        }
        if (\array_key_exists('const', $schema)) {
            $expression = self::literal($schema['const'], $where);

            return [$nullable ? $expression . '|null' : $expression, []];
        }
        if (\array_key_exists('enum', $schema)) {
            return $this->renderEnum($schema, $hint, $where, $nullable, $top);
        }
        if (\count($types) > 1) {
            throw new GenerationError("{$where}: several non-null types");
        }
        if ($nullable && $types === []) {
            return ['null', []];
        }
        [$expression, $dependencies] = $this->renderKind($schema, $types[0] ?? null, $hint, $where);

        return [$nullable ? self::union([$expression, 'null']) : $expression, $dependencies];
    }

    /**
     * @param array<string, mixed> $schema
     *
     * @return array{string, list<string>}
     */
    private function renderKind(array $schema, ?string $kind, string $hint, string $where): array
    {
        if ($kind !== null && \array_key_exists($kind, self::SCALARS)) {
            return [self::SCALARS[$kind], []];
        }
        if ($kind === 'array') {
            $items = self::schema($schema['items'] ?? [], "{$where}.items");
            [$expression, $dependencies] = $this->render($items, "{$hint}Item", "{$where}.items");

            return ["list<{$expression}>", $dependencies];
        }
        if ($kind === 'object' || ($kind === null && \array_key_exists('properties', $schema))) {
            return $this->renderObject($schema, $hint, $where);
        }
        if ($kind === null && array_diff(array_keys($schema), self::ANNOTATION_KEYWORDS) === []) {
            return ['mixed', []];
        }

        throw new GenerationError("{$where}: unsupported type " . var_export($kind, true));
    }

    /**
     * @param array<string, mixed> $schema
     *
     * @return array{string, list<string>}
     */
    private function renderEnum(array $schema, string $hint, string $where, bool $nullable, bool $top): array
    {
        $values = self::list($schema['enum'] ?? null, "{$where}.enum");
        $members = [];
        foreach ($values as $value) {
            if ($value === null) {
                $nullable = true;

                continue;
            }
            $members[] = self::literal($value, $where);
        }
        if ($members === []) {
            throw new GenerationError("{$where}: an enum with no values");
        }
        $expression = self::union($members);
        if ($top) {
            return [$nullable ? self::union([...$members, 'null']) : $expression, []];
        }
        $this->define(new Definition($hint, $expression));

        return [$nullable ? "{$hint}|null" : $hint, [$hint]];
    }

    /**
     * @param array<string, mixed> $schema
     *
     * @return array{string, list<string>}
     */
    private function renderCombination(array $schema, string $combinator, string $hint, string $where): array
    {
        $structure = array_diff(
            array_intersect(array_keys($schema), self::STRUCTURE_KEYWORDS),
            [$combinator, 'discriminator'],
        );
        if ($structure !== []) {
            sort($structure);

            throw new GenerationError("{$where}: {$combinator} with " . implode(', ', $structure));
        }
        $members = [];
        foreach (self::list($schema[$combinator] ?? null, $where) as $member) {
            $members[] = self::schema($member, $where);
        }
        if ($combinator === 'allOf' && \count($members) !== 1) {
            throw new GenerationError("{$where}: allOf is only supported with one member");
        }
        $expressions = [];
        $dependencies = [];
        foreach ($members as $index => $member) {
            [$expression, $memberDependencies] = $this->render($member, $hint, "{$where}.{$combinator}[{$index}]");
            $expressions[] = $expression;
            $dependencies = [...$dependencies, ...$memberDependencies];
        }
        if (\array_key_exists('discriminator', $schema)) {
            $this->checkDiscriminator($schema, $members, $where);
        }

        return [self::union($expressions), $dependencies];
    }

    /**
     * A discriminated union narrows on its property: every mapping must match the members.
     *
     * @param array<string, mixed> $schema
     * @param list<array<string, mixed>> $members
     */
    private function checkDiscriminator(array $schema, array $members, string $where): void
    {
        $discriminator = self::schema($schema['discriminator'] ?? null, "{$where}.discriminator");
        $property = self::string($discriminator['propertyName'] ?? null, "{$where}.discriminator.propertyName");
        $mapping = self::schema($discriminator['mapping'] ?? [], "{$where}.discriminator.mapping");
        $referenced = [];
        foreach ($members as $member) {
            if (\array_key_exists('$ref', $member)) {
                $referenced[] = $this->reference($member, $where);
            }
        }
        if (\count($referenced) !== \count($members)) {
            throw new GenerationError("{$where}: a discriminated union must list references only");
        }
        foreach ($mapping as $value => $target) {
            $targetName = self::string($target, $where);
            if (str_starts_with($targetName, self::COMPONENT_PREFIX)) {
                $targetName = substr($targetName, \strlen(self::COMPONENT_PREFIX));
            }
            if (!\in_array($targetName, $referenced, true)) {
                throw new GenerationError("{$where}: mapping {$value} points outside the union");
            }
            $properties = self::schema(self::schema($this->schemas[$targetName] ?? null, $targetName)['properties'] ?? [], $targetName);
            $discriminant = self::schema($properties[$property] ?? [], "{$targetName}.{$property}");
            $allowed = \array_key_exists('enum', $discriminant)
                ? self::list($discriminant['enum'], "{$targetName}.{$property}")
                : [$discriminant['const'] ?? null];
            if (!\in_array((string) $value, $allowed, true)) {
                throw new GenerationError("{$where}: {$targetName}.{$property} does not allow {$value}");
            }
        }
    }

    /**
     * @param array<string, mixed> $schema
     *
     * @return array{string, list<string>}
     */
    private function renderObject(array $schema, string $hint, string $where): array
    {
        $extra = $schema['additionalProperties'] ?? null;
        if (!\array_key_exists('properties', $schema)) {
            if (\is_array($extra)) {
                [$expression, $dependencies] = $this->render(
                    self::schema($extra, "{$where}.additionalProperties"),
                    "{$hint}Value",
                    "{$where}.additionalProperties",
                );

                return ["array<string, {$expression}>", $dependencies];
            }

            return ['array<string, mixed>', []];
        }
        $this->defineShape($hint, $schema, $where);

        return [$hint, [$hint]];
    }

    // Definitions.

    private function define(Definition $definition): void
    {
        $name = $definition->name;
        if (\array_key_exists($name, $this->definitions)) {
            throw new GenerationError("Two definitions are named {$name}");
        }
        if (preg_match('/^[A-Za-z_][A-Za-z0-9_]*\z/', $name) !== 1 || \in_array(strtolower($name), self::RESERVED_NAMES, true)) {
            throw new GenerationError("{$name} cannot be the name of a type alias");
        }
        $this->definitions[$name] = $definition;
    }

    /**
     * @param array<string, mixed> $schema
     */
    private function defineShape(string $name, array $schema, string $where): void
    {
        $unexpected = array_intersect(array_keys($schema), ['allOf', 'anyOf', 'oneOf', 'enum', 'const', 'items']);
        if ($unexpected !== [] || !\in_array($this->typesOf($schema, $where), [[], ['object']], true)) {
            throw new GenerationError("{$where}: properties mixed with other types");
        }
        if (\array_key_exists('not', $schema)) {
            $this->checkNot($schema, $where);
        }
        $extra = $schema['additionalProperties'] ?? null;
        if (!\in_array($extra, [null, true, false], true)) {
            throw new GenerationError("{$where}: typed members with typed additionalProperties");
        }
        $properties = self::schema($schema['properties'] ?? [], "{$where}.properties");
        $required = [];
        foreach (self::list($schema['required'] ?? [], $where) as $key) {
            $required[] = self::string($key, $where);
        }
        $missing = array_diff($required, array_map('strval', array_keys($properties)));
        if ($missing !== []) {
            throw new GenerationError("{$where}: required members without a schema: " . implode(', ', $missing));
        }
        // Defined before its members, so a second definition with the same name fails at once.
        $definition = new Definition($name, null, [], [], $extra === true);
        $this->define($definition);
        foreach ($properties as $key => $value) {
            $key = (string) $key;
            [$expression, $dependencies] = $this->render(
                self::schema($value, "{$where}.{$key}"),
                $name . ucfirst($key),
                "{$where}.{$key}",
            );
            $definition->fields[] = new Field($key, $expression, \in_array($key, $required, true));
            $definition->dependencies = [...$definition->dependencies, ...$dependencies];
        }
    }

    /**
     * `not: {required: [...]}` forbids members: a sealed shape leaves them out.
     *
     * @param array<string, mixed> $schema
     */
    private function checkNot(array $schema, string $where): void
    {
        $forbidden = self::schema($schema['not'] ?? null, "{$where}.not");
        if (array_keys($forbidden) !== ['required']) {
            throw new GenerationError("{$where}: `not` is only supported as not.required");
        }
        $properties = self::schema($schema['properties'] ?? [], $where);
        foreach (self::list($forbidden['required'] ?? null, "{$where}.not.required") as $key) {
            $key = self::string($key, $where);
            if (\array_key_exists($key, $properties)) {
                throw new GenerationError("{$where}: {$key} is both declared and forbidden");
            }
        }
    }

    /**
     * @param array<string, mixed> $schema
     */
    private function defineComponent(string $name, array $schema): void
    {
        $where = "components.schemas.{$name}";
        $this->checkKeywords($schema, $where);
        if (\array_key_exists('properties', $schema)) {
            $this->defineShape($name, $schema, $where);

            return;
        }
        [$expression, $dependencies] = $this->render($schema, $name, $where, true);
        $this->define(new Definition($name, $expression, [], $dependencies));
    }

    /**
     * A shape for the query of every operation that takes one, named after the operation.
     */
    private function defineQueries(): void
    {
        $paths = self::schema($this->document['paths'] ?? [], 'paths');
        foreach ($paths as $path => $item) {
            foreach (self::schema($item, (string) $path) as $method => $value) {
                if (!\in_array($method, ['get', 'post', 'put', 'patch', 'delete'], true)) {
                    continue;
                }
                $operation = self::schema($value, "{$method} {$path}");
                $operationId = self::string($operation['operationId'] ?? null, "{$method} {$path}");
                $definition = new Definition(ucfirst($operationId) . 'Query', null);
                foreach (self::list($operation['parameters'] ?? [], $operationId) as $raw) {
                    $parameter = $this->parameter(self::schema($raw, $operationId), $operationId);
                    if (($parameter['in'] ?? null) !== 'query') {
                        continue;
                    }
                    $key = self::string($parameter['name'] ?? null, $operationId);
                    $where = "{$operationId}.{$key}";
                    [$expression, $dependencies] = $this->render(
                        self::schema($parameter['schema'] ?? [], $where),
                        $definition->name . ucfirst($key),
                        $where,
                    );
                    $definition->fields[] = new Field($key, $expression, ($parameter['required'] ?? false) === true);
                    $definition->dependencies = [...$definition->dependencies, ...$dependencies];
                }
                if ($definition->fields !== []) {
                    $this->define($definition);
                }
            }
        }
    }

    /**
     * @param array<string, mixed> $parameter
     *
     * @return array<string, mixed>
     */
    private function parameter(array $parameter, string $where): array
    {
        if (!\array_key_exists('$ref', $parameter)) {
            return $parameter;
        }
        $target = self::string($parameter['$ref'], $where);
        $name = substr($target, \strlen(self::PARAMETER_PREFIX));
        if (!str_starts_with($target, self::PARAMETER_PREFIX) || !\array_key_exists($name, $this->parameters)) {
            throw new GenerationError("{$where}: unknown parameter {$target}");
        }

        return self::schema($this->parameters[$name], $target);
    }

    // Checks.

    /**
     * @param array<string, mixed> $schema
     */
    private function checkKeywords(array $schema, string $where): void
    {
        $unknown = array_diff(array_keys($schema), self::ANNOTATION_KEYWORDS, self::STRUCTURE_KEYWORDS);
        if ($unknown !== []) {
            sort($unknown);

            throw new GenerationError("{$where}: unsupported keywords " . implode(', ', $unknown));
        }
    }

    /**
     * @param array<string, mixed> $schema
     */
    private function reference(array $schema, string $where): string
    {
        $target = self::string($schema['$ref'] ?? null, $where);
        $name = substr($target, \strlen(self::COMPONENT_PREFIX));
        if (!str_starts_with($target, self::COMPONENT_PREFIX) || !\array_key_exists($name, $this->schemas)) {
            throw new GenerationError("{$where}: unknown reference {$target}");
        }
        if (\count(array_diff(array_keys($schema), self::ANNOTATION_KEYWORDS)) > 1) {
            throw new GenerationError("{$where}: \$ref with sibling keywords");
        }

        return $name;
    }

    /**
     * @param array<string, mixed> $schema
     *
     * @return list<string>
     */
    private function typesOf(array $schema, string $where): array
    {
        $declared = $schema['type'] ?? null;
        if ($declared === null) {
            return [];
        }
        if (\is_string($declared)) {
            return [$declared];
        }
        $types = [];
        foreach (self::list($declared, $where) as $type) {
            $types[] = self::string($type, $where);
        }

        return $types;
    }

    /**
     * Refuses an alias that refers to itself: PHPStan cannot resolve one.
     */
    private function checkCycles(): void
    {
        $done = [];
        $visiting = [];
        $visit = function (string $name) use (&$visit, &$done, &$visiting): void {
            if (isset($done[$name])) {
                return;
            }
            if (isset($visiting[$name])) {
                throw new GenerationError("{$name} refers to itself: recursive types are not supported");
            }
            $visiting[$name] = true;
            foreach ($this->definitions[$name]->dependencies ?? [] as $dependency) {
                $visit($dependency);
            }
            unset($visiting[$name]);
            $done[$name] = true;
        };
        foreach (array_keys($this->definitions) as $name) {
            $visit($name);
        }
    }

    // Output.

    /**
     * The lines of one `@phpstan-type`, without the docblock's leading ` * `.
     *
     * @return list<string>
     */
    private function emit(Definition $definition): array
    {
        $prefix = "@phpstan-type {$definition->name} ";
        if ($definition->expression !== null) {
            $line = $prefix . $definition->expression;
            $members = self::splitUnion($definition->expression);
            if (\strlen(' * ' . $line) <= self::LINE_LENGTH || \count($members) < 2) {
                return [$line];
            }
            $lines = [$prefix . $members[0]];
            foreach (\array_slice($members, 1) as $member) {
                $lines[] = self::INDENT . '|' . $member;
            }

            return $lines;
        }
        if ($definition->fields === [] && !$definition->open) {
            return [$prefix . 'array{}'];
        }
        $lines = [$prefix . 'array{'];
        foreach ($definition->fields as $field) {
            $optional = $field->required ? '' : '?';
            $lines[] = self::INDENT . self::key($field->name) . "{$optional}: {$field->type},";
        }
        if ($definition->open) {
            // additionalProperties: true. Members the document does not declare may appear.
            $lines[] = self::INDENT . '...<string, mixed>';
        }
        $lines[] = '}';

        return $lines;
    }

    /**
     * @param list<string> $members
     */
    private static function union(array $members): string
    {
        $parts = [];
        foreach ($members as $member) {
            foreach (self::splitUnion($member) as $part) {
                $parts[] = $part;
            }
        }
        $unique = array_values(array_unique($parts));
        if (\in_array('null', $unique, true)) {
            $unique = [...array_values(array_filter($unique, static fn(string $part): bool => $part !== 'null')), 'null'];
        }

        return implode('|', $unique);
    }

    /**
     * The members of a union, split on the `|` outside brackets and quotes.
     *
     * @return list<string>
     */
    private static function splitUnion(string $expression): array
    {
        $parts = [];
        $depth = 0;
        $current = '';
        $length = \strlen($expression);
        for ($index = 0; $index < $length; $index++) {
            $char = $expression[$index];
            if ($char === "'") {
                $end = $index + 1;
                while ($end < $length && $expression[$end] !== "'") {
                    $end += $expression[$end] === '\\' ? 2 : 1;
                }
                $current .= substr($expression, $index, $end - $index + 1);
                $index = $end;

                continue;
            }
            if ($char === '<' || $char === '{' || $char === '(') {
                $depth++;
            } elseif ($char === '>' || $char === '}' || $char === ')') {
                $depth--;
            }
            if ($char === '|' && $depth === 0) {
                $parts[] = $current;
                $current = '';

                continue;
            }
            $current .= $char;
        }
        $parts[] = $current;

        return $parts;
    }

    private static function literal(mixed $value, string $where): string
    {
        if (\is_bool($value)) {
            return $value ? 'true' : 'false';
        }
        if (\is_int($value)) {
            return (string) $value;
        }
        if (\is_string($value)) {
            // Written inside a PHPDoc comment: `*/` would end it and turn the rest into PHP code,
            // and a line break would start a tag of its own.
            if (str_contains($value, '*/') || preg_match('/[\x00-\x1f\x7f]/', $value) === 1) {
                throw new GenerationError("{$where}: " . json_encode($value, \JSON_INVALID_UTF8_SUBSTITUTE | \JSON_UNESCAPED_SLASHES | \JSON_UNESCAPED_UNICODE) . ' cannot be written in a PHPDoc comment');
            }

            return "'" . str_replace(['\\', "'"], ['\\\\', "\\'"], $value) . "'";
        }

        throw new GenerationError("{$where}: enum values must be strings, integers or booleans");
    }

    private static function key(string $name): string
    {
        return preg_match('/^[A-Za-z_][A-Za-z0-9_]*\z/', $name) === 1 ? $name : self::literal($name, $name);
    }

    /**
     * @return array<string, mixed>
     */
    private static function schema(mixed $value, string $where): array
    {
        if (!\is_array($value) || ($value !== [] && array_is_list($value))) {
            throw new GenerationError("{$where}: expected a schema object");
        }
        $schema = [];
        foreach ($value as $key => $member) {
            $schema[(string) $key] = $member;
        }

        return $schema;
    }

    /**
     * @return list<mixed>
     */
    private static function list(mixed $value, string $where): array
    {
        if (!\is_array($value) || !array_is_list($value)) {
            throw new GenerationError("{$where}: expected a list");
        }

        return $value;
    }

    private static function string(mixed $value, string $where): string
    {
        if (!\is_string($value)) {
            throw new GenerationError("{$where}: expected a string");
        }

        return $value;
    }
